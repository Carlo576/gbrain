/**
 * guard_functions doctor check (#7632): guardFunctionProblems names each guard drift with SQL that clears it. The
 * Postgres non-owner path is in test/e2e/guard-definer-postgres.test.ts (case 11).
 */
import { afterAll, beforeAll, describe, expect, test } from 'bun:test';
import { PGLiteEngine } from '../src/core/pglite-engine.ts';
import { guardFunctionProblems } from '../src/commands/doctor/checks/guard-functions.ts';
import { derivationScopeLockSql } from '../src/core/page-body/schema.ts';

describe('guard_functions doctor check (#7632)', () => {
  let engine: PGLiteEngine;
  beforeAll(async () => {
    engine = new PGLiteEngine();
    await engine.connect({});
    await engine.initSchema();
  }, 120_000);
  afterAll(async () => { await engine?.disconnect(); });

  test('a fresh install has no problem', async () => {
    expect(await guardFunctionProblems(engine)).toEqual({ problems: [], fix: [] });
  });

  test('each drift is named, and running the printed fix clears every one', async () => {
    await engine.runMigration(0, `ALTER FUNCTION gbrain_refuse_purged_page() SECURITY INVOKER SET search_path = pg_catalog, public;
      GRANT EXECUTE ON FUNCTION gbrain_refuse_purged_take() TO PUBLIC;
      DROP TRIGGER pages_refuse_purged ON pages;
      CREATE TRIGGER pages_refuse_purged BEFORE INSERT OR UPDATE ON pages FOR EACH ROW EXECUTE FUNCTION gbrain_refuse_purged_page();
      DROP TRIGGER page_segment_derivations_refuse_stored_purging ON page_segment_derivations;
      ALTER FUNCTION gbrain_try_jsonb(text) SET search_path = pg_catalog, public;`);
    const { problems, fix } = await guardFunctionProblems(engine);
    expect(problems).toEqual([
      'gbrain_refuse_purged_page() is not SECURITY DEFINER with search_path pg_catalog, pg_temp',
      'gbrain_refuse_purged_take() is executable by PUBLIC',
      'pages_refuse_purged on pages still fires BEFORE ROW',
      'page_segment_derivations has no page_segment_derivations_refuse_stored_purging AFTER check',
      '1 function(s) pin search_path without pg_temp last (gbrain_try_jsonb(text))',
    ]);
    await engine.runMigration(0, fix.join('\n'));
    expect(await guardFunctionProblems(engine)).toEqual({ problems: [], fix: [] });
  });

  // Generated by gstack /ship coverage audit (#7642).
  // Value: protects=doctor names a stored-derivation check that fires BEFORE ROW (a definer raising before RLS) and its fix
  // moves it AFTER ROW; fails_when=the trigger probe accepts page_segment_derivations_refuse_stored_purging at any timing;
  // why_new=the drift test above only drops the trigger; seam=none; no_claim=the RLS oracle itself (PGLite has one role;
  // e2e case 8 covers it)
  test('a stored-derivation check that fires BEFORE ROW is named, and the fix moves it AFTER ROW', async () => {
    await engine.runMigration(0, `DROP TRIGGER page_segment_derivations_refuse_stored_purging ON page_segment_derivations;
      CREATE TRIGGER page_segment_derivations_refuse_stored_purging BEFORE INSERT OR UPDATE OF output, receipt ON page_segment_derivations
        FOR EACH ROW EXECUTE FUNCTION gbrain_refuse_stored_purging_derivation();`);
    const { problems, fix } = await guardFunctionProblems(engine);
    expect(problems).toEqual(['page_segment_derivations_refuse_stored_purging on page_segment_derivations still fires BEFORE ROW']);
    await engine.runMigration(0, fix.join('\n'));
    expect(await guardFunctionProblems(engine)).toEqual({ problems: [], fix: [] });
  });

  // An older gbrain booting against an upgraded brain replays its schema blob, whose CREATE OR REPLACE of the scope-entry
  // function (as on master before #7632) makes it an invoker again: doctor names it and its fix restores the definer.
  test('a scope-entry function an older gbrain re-created as an invoker is named, and the fix restores the definer', async () => {
    await engine.runMigration(0, `CREATE OR REPLACE FUNCTION gbrain_mark_derivation_scope_entry() RETURNS trigger SET search_path = pg_catalog, public AS $func$
DECLARE
  src TEXT;
  page INTEGER;
BEGIN
  IF TG_TABLE_NAME = 'pages' THEN
    src := NEW.source_id;
    page := NEW.id;
  ELSE
    src := OLD.source_id;
    page := OLD.page_id;
  END IF;
  PERFORM pg_advisory_xact_lock_shared(${derivationScopeLockSql('src')});
  INSERT INTO page_segment_derivation_purge_pages (request_id, page_id)
    SELECT x.request_id, page FROM page_segment_derivation_purges x WHERE x.source_id = src ON CONFLICT DO NOTHING;
  RETURN NULL;
END
$func$ LANGUAGE plpgsql;`);
    const { problems, fix } = await guardFunctionProblems(engine);
    expect(problems).toEqual(['gbrain_mark_derivation_scope_entry() is not SECURITY DEFINER with search_path pg_catalog, pg_temp']);
    await engine.runMigration(0, fix.join('\n'));
    expect(await guardFunctionProblems(engine)).toEqual({ problems: [], fix: [] });
    const [fn] = await engine.executeRaw<{ secdef: boolean; config: string[] }>(
      `SELECT prosecdef AS secdef, proconfig AS config FROM pg_proc WHERE oid = 'gbrain_mark_derivation_scope_entry()'::regprocedure`);
    expect(fn).toEqual({ secdef: true, config: ['search_path=pg_catalog, pg_temp'] });
  });

  // Generated by gstack /ship coverage audit (#7642).
  // Value: protects=doctor asks for the stored-derivation check only where page_segment_derivations exists, so its fix never
  // targets a missing table; fails_when=the to_regclass presence probe is dropped; why_new=every other doctor test has the
  // table; seam=none; no_claim=a real pre-v273 Postgres brain (a dropped table on PGLite stands in)
  test('a brain without page_segment_derivations is not asked for its check', async () => {
    const bare = new PGLiteEngine();
    try {
      await bare.connect({});
      await bare.initSchema();
      await bare.runMigration(0, 'DROP TABLE page_segment_derivations CASCADE');
      expect(await guardFunctionProblems(bare)).toEqual({ problems: [], fix: [] });
    } finally {
      await bare.disconnect();
    }
  }, 120_000);
});
